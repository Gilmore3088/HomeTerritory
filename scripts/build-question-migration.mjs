// Generates the curated-question-bank migration from data/question-bank.json.
// Run from the repo root: node scripts/build-question-migration.mjs > supabase/migrations/<timestamp>_curated_question_bank.sql
import { readFileSync } from "node:fs";

const bank = JSON.parse(readFileSync(new URL("../data/question-bank.json", import.meta.url), "utf8")).questions;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const textArray = (items) => `array[${items.map(q).join(",")}]::text[]`;

const rows = [];
for (const [state, questions] of Object.entries(bank)) {
  for (const question of questions) {
    const options = question.f === "mc" ? JSON.stringify(question.o) : "[]";
    rows.push(
      `(${q(state)}, ${q(question.sport)}, 'curated', ${question.t}, ${q(question.f === "mc" ? "multiple_choice" : "free_fill")}, ${q(question.q)}, ${q(options)}::jsonb, ${q(question.a)}, ${textArray(question.al ?? [])})`,
    );
  }
}

console.log(`-- Curated question bank (generated by scripts/build-question-migration.mjs from data/question-bank.json).
-- Replaces the trivial starter_seed bank: real tiered trivia, 5 questions per state.
-- Also: when a player has seen every question for a state, recycle the least
-- recently served one instead of failing the action.

update public.questions set active = false where validation_status = 'starter_seed';

insert into public.questions(territory_id, sport, link_type, tier, format, question_text, options, correct_answer, aliases, validation_status)
select v.territory_id, v.sport, v.link_type, v.tier, v.format, v.question_text, v.options, v.correct_answer, v.aliases, 'curated_v1'
from (values
${rows.join(",\n")}
) as v(territory_id, sport, link_type, tier, format, question_text, options, correct_answer, aliases);

create or replace function public.pick_next_question(p_session_id uuid)
returns jsonb
language plpgsql
security definer set search_path = public
as $fn$
declare
  v_session public.game_sessions;
  v_question public.questions;
  v_attempt uuid;
  v_expires timestamptz;
  v_options jsonb;
  v_sports text[];
begin
  select gs.* into v_session from public.game_sessions gs where gs.id = p_session_id for update;
  select g.sports into v_sports from public.seasons s join public.groups g on g.id = s.group_id where s.id = v_session.season_id;

  select qq.* into v_question
  from public.questions qq
  where qq.territory_id = v_session.territory_id
    and qq.active
    and not exists(
      select 1 from public.season_question_seen sqs
      where sqs.season_id = v_session.season_id and sqs.question_id = qq.id and sqs.served_to = v_session.user_id
    )
  order by case when qq.sport = any(v_sports) then 0 else 1 end, abs(qq.tier - v_session.tier), random()
  limit 1;

  if not found then
    -- Every question for this state has been seen by this player: recycle the
    -- least recently served one rather than making the state unplayable.
    select qq.* into v_question
    from public.questions qq
    join public.season_question_seen sqs
      on sqs.season_id = v_session.season_id and sqs.question_id = qq.id and sqs.served_to = v_session.user_id
    where qq.territory_id = v_session.territory_id and qq.active
    order by sqs.served_at asc, abs(qq.tier - v_session.tier)
    limit 1;
    if not found then raise exception 'This state is temporarily out of unused questions'; end if;
    update public.season_question_seen set served_at = now()
    where season_id = v_session.season_id and question_id = v_question.id and served_to = v_session.user_id;
  else
    insert into public.season_question_seen(season_id, question_id, served_to) values (v_session.season_id, v_question.id, v_session.user_id);
  end if;

  v_expires := now() + case when v_question.tier = 3 then interval '45 seconds' else interval '30 seconds' end;
  insert into public.question_attempts(session_id, question_id, user_id, expires_at)
  values (p_session_id, v_question.id, v_session.user_id, v_expires) returning id into v_attempt;
  update public.game_sessions set current_attempt_id = v_attempt where id = p_session_id;

  select coalesce(jsonb_agg(value order by md5(value || v_attempt::text)), '[]'::jsonb) into v_options
  from jsonb_array_elements_text(v_question.options);

  return jsonb_build_object(
    'attempt_id', v_attempt,
    'text', v_question.question_text,
    'format', v_question.format,
    'options', v_options,
    'tier', v_question.tier,
    'sport', v_question.sport,
    'link_type', v_question.link_type,
    'expires_at', v_expires
  );
end;
$fn$;`);
